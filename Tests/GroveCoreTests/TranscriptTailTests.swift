import XCTest
@testable import GroveCore

/// A session's preview, read from the end of its transcript: the last prompt, the last
/// reply, the name, and where the turn stands.
final class TranscriptTailTests: XCTestCase {
    private var root: URL!

    override func setUpWithError() throws {
        root = try Fixture.tempDir("transcript-tail")
    }

    private func preview(_ builder: TranscriptBuilder, file: String = #function) throws -> SessionPreview? {
        let url = root.appendingPathComponent(file.filter { $0.isLetter } + ".jsonl")
        try builder.write(to: url)
        return TranscriptTail.preview(path: url.path)
    }

    func testTheLastPromptAndReplyAndTheGeneratedName() throws {
        var b = TranscriptBuilder()
        b.aiTitle = "Retry uploads on flaky networks"
        b.prompt("Why does the upload stall at 99%?", at: 0)
        b.reply("The progress callback fires before the server confirms.", at: 5)
        b.prompt("Fix it, and keep the bar honest", at: 60)
        b.thinking(at: 61)
        b.reply("## Fixed\n\n- The bar now waits for the **server's** reply.\n- `UploadTask` retries twice.", at: 90)
        b.turnEnd(at: 91)
        b.appendMetadata()
        let p = try XCTUnwrap(preview(b))
        XCTAssertEqual(p.prompt, "Fix it, and keep the bar honest")
        XCTAssertEqual(p.reply, "Fixed The bar now waits for the server's reply. UploadTask retries twice.")
        XCTAssertEqual(p.title, "Retry uploads on flaky networks")
        XCTAssertEqual(p.turn, .answered)
        XCTAssertEqual(p.at, Date(timeIntervalSince1970: 1_792_000_090), "the newest message, not the turn's end")
    }

    func testANameGivenByTheUserWinsAndAnEmptyOneFallsBack() throws {
        var b = TranscriptBuilder()
        b.aiTitle = "Generated"
        b.customTitle = "Upload fixes"
        b.prompt("go", at: 0)
        b.reply("ok", at: 1)
        b.appendMetadata()
        XCTAssertEqual(try preview(b)?.title, "Upload fixes")
        b.customTitle = ""
        b.appendMetadata()
        XCTAssertEqual(try preview(b, file: "cleared")?.title, "Generated", "an empty custom title is no custom title")
    }

    func testWhereTheTurnStands() throws {
        var working = TranscriptBuilder()
        working.prompt("Run the tests", at: 0)
        XCTAssertEqual(try preview(working, file: "prompted")?.turn, .working)

        var tool = working
        tool.toolCall("Bash", input: ["command": "swift test"], at: 1)
        let pending = try XCTUnwrap(preview(tool, file: "tool"))
        XCTAssertEqual(pending.turn, .tool)
        XCTAssertEqual(pending.tool, "Bash")
        XCTAssertEqual(pending.prompt, "Run the tests")
        XCTAssertNil(pending.reply)

        var result = tool
        result.toolResult(bytes: 200, at: 2)
        XCTAssertEqual(try preview(result, file: "result")?.turn, .working, "a result came back: Claude's move")

        var stopped = result
        stopped.interrupt(at: 3)
        XCTAssertEqual(try preview(stopped, file: "stopped")?.turn, .interrupted)
        XCTAssertEqual(try preview(stopped, file: "stopped2")?.prompt, "Run the tests", "an interruption is not a prompt")

        var failed = result
        failed.apiError(at: 3)
        let error = try XCTUnwrap(preview(failed, file: "failed"))
        XCTAssertEqual(error.turn, .failed)
        XCTAssertNil(error.reply, "the error text is not Claude's reply")
    }

    /// Entries that are not the conversation: command caveats, command output, reminders,
    /// a subagent's messages, progress entries. None of them is the prompt or the reply.
    func testWrappersMetaAndSidechainsAreNotThePreview() throws {
        var b = TranscriptBuilder()
        b.prompt("Tidy the upload module", at: 0)
        b.reply("Tidied: three helpers merged into one.", at: 10)
        b.meta("<local-command-caveat>Caveat: the messages below were generated by the user while running local commands.</local-command-caveat>", at: 20)
        b.prompt("<command-name>/model</command-name>\n<command-message>model</command-message>\n<command-args></command-args>", at: 21)
        b.prompt("<local-command-stdout>Set model to opus</local-command-stdout>", at: 22)
        b.progress(at: 23)
        b.sidechainReply("a subagent's own words", at: 24)
        let p = try XCTUnwrap(preview(b))
        XCTAssertEqual(p.prompt, "Tidy the upload module")
        XCTAssertEqual(p.reply, "Tidied: three helpers merged into one.")
    }

    func testCustomCommandsAndShellLinesReadAsTheSessionListShowsThem() {
        XCTAssertEqual(TranscriptTail.promptLine("<command-name>/review</command-name>\n<command-args>the upload PR</command-args>"),
                       "/review the upload PR")
        XCTAssertNil(TranscriptTail.promptLine("<command-name>/clear</command-name><command-args></command-args>"))
        XCTAssertEqual(TranscriptTail.promptLine("<bash-input>git status</bash-input>"), "! git status")
        XCTAssertNil(TranscriptTail.promptLine("<system-reminder>ambient</system-reminder>"))
        XCTAssertNil(TranscriptTail.promptLine("[Request interrupted by user for tool use]"))
        XCTAssertEqual(TranscriptTail.promptLine("  two\nlines  "), "two lines")
    }

    func testLongTextIsCutAtACharacterWithAnEllipsis() {
        let long = String(repeating: "загрузка ", count: 60)   // Cyrillic: several bytes a character
        let line = TranscriptTail.oneLine(long)!
        XCTAssertEqual(line.count, TranscriptTail.length + 1)
        XCTAssertTrue(line.hasSuffix("\u{2026}"))
        XCTAssertEqual(TranscriptTail.oneLine("👩🏽‍💻" + String(repeating: "a", count: 300))?.first, "👩🏽‍💻")
    }

    func testCodeBlocksTablesAndRulesAreLeftOutOfTheReply() {
        XCTAssertEqual(TranscriptTail.replyLine("Run this:\n```sh\nswift test\n```\n| a | b |\n|---|---|\n---\n> Note: done"),
                       "Run this: Note: done")
        XCTAssertNil(TranscriptTail.replyLine("```\nonly code\n```"))
    }

    /// The window starts mid-file: its first piece is half a line and is not read. The
    /// last line is still being written: it does not parse and is skipped.
    func testATornFirstAndLastLineAreSkipped() throws {
        var b = TranscriptBuilder.long(bytes: 300 << 10)
        b.prompt("The newest prompt", at: 100_000)
        b.reply("The newest reply", at: 100_001)
        b.raw(#"{"parentUuid":"x","type":"assistant","message":{"content":[{"type":"text","text":"half-writ"#)
        let url = root.appendingPathComponent("torn.jsonl")
        try Data(b.lines.joined(separator: "\n").utf8).write(to: url)    // no final newline
        let p = try XCTUnwrap(TranscriptTail.preview(path: url.path))
        XCTAssertEqual(p.prompt, "The newest prompt")
        XCTAssertEqual(p.reply, "The newest reply")
    }

    /// A pasted screenshot bigger than the window: the window grows until the prompt
    /// with it is whole, and Claude's reply after it is still found.
    func testAnEntryBiggerThanTheWindowIsReadWhole() throws {
        var b = TranscriptBuilder.long(bytes: 200 << 10)
        b.stampsMetadata = false
        b.promptWithImage("What is wrong in this screenshot?", imageBytes: 300 << 10, at: 100_000)
        let p = try XCTUnwrap(preview(b))
        XCTAssertEqual(p.prompt, "What is wrong in this screenshot?")
        XCTAssertEqual(p.turn, .working)
        XCTAssertNotNil(p.reply, "the reply before the screenshot")
    }

    /// No prompt in the window (a long run of tool calls): the `last-prompt` record that
    /// Claude Code keeps writing at the end stands in.
    func testTheLastPromptRecordStandsInForAPromptOutOfTheWindow() throws {
        var b = TranscriptBuilder()
        b.prompt("Refactor the whole uploader", at: 0)
        for i in 0..<40 {
            b.toolCall("Edit", input: ["file_path": "/Users/demo/Code/harbor/Sources/File\(i).swift"], at: i + 1)
            b.toolResult(bytes: 4_000, at: i + 1)
        }
        let p = try XCTUnwrap(preview(b))
        XCTAssertEqual(p.prompt, "Refactor the whole uploader")
        XCTAssertEqual(p.turn, .working)
    }

    func testEmptyMissingAndGarbledFilesHaveNoPreview() throws {
        XCTAssertNil(TranscriptTail.preview(path: root.appendingPathComponent("none.jsonl").path))
        let empty = root.appendingPathComponent("empty.jsonl")
        try Data().write(to: empty)
        XCTAssertNil(TranscriptTail.preview(path: empty.path))
        let garbled = root.appendingPathComponent("garbled.jsonl")
        try Data("not json\n{\"type\":\"user\"\n\u{0}\u{0}\n".utf8).write(to: garbled)
        XCTAssertNil(TranscriptTail.preview(path: garbled.path))
        XCTAssertNil(TranscriptTail.preview(path: root.path), "a folder is not a transcript")
    }
}
